-- =====================================================================
-- 01_Esquema_y_Datos.sql
-- Proyecto de Base de Datos para un E-commerce  (MySQL 8.0.19+)
-- Contiene: estructura completa (CREATE TABLE) y datos de ejemplo (INSERT).
-- =====================================================================
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP DATABASE IF EXISTS ecommerce_db;
CREATE DATABASE ecommerce_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ecommerce_db;

-- ---------------------------------------------------------------------
-- Tablas maestras
-- ---------------------------------------------------------------------
CREATE TABLE sucursales (
  id_sucursal  INT AUTO_INCREMENT PRIMARY KEY,
  nombre       VARCHAR(100) NOT NULL UNIQUE,
  ciudad       VARCHAR(80)  NOT NULL
) ENGINE=InnoDB;

CREATE TABLE categorias (
  id_categoria       INT AUTO_INCREMENT PRIMARY KEY,
  nombre             VARCHAR(80) NOT NULL UNIQUE,
  descripcion        TEXT NULL,
  id_categoria_padre INT NULL,                       -- jerarquía (categoría -> subcategoría)
  total_productos    INT NOT NULL DEFAULT 0,         -- contador mantenido por triggers
  CONSTRAINT fk_cat_padre FOREIGN KEY (id_categoria_padre)
    REFERENCES categorias (id_categoria) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE proveedores (
  id_proveedor      INT AUTO_INCREMENT PRIMARY KEY,
  nombre            VARCHAR(120) NOT NULL,
  email_contacto    VARCHAR(150) NULL UNIQUE,
  telefono_contacto VARCHAR(30)  NULL
) ENGINE=InnoDB;

CREATE TABLE productos (
  id_producto        INT AUTO_INCREMENT PRIMARY KEY,
  nombre             VARCHAR(150) NOT NULL UNIQUE,
  descripcion        TEXT NULL,
  precio             DECIMAL(12,2) NOT NULL,
  costo              DECIMAL(12,2) NOT NULL,
  stock              INT NOT NULL DEFAULT 0,
  stock_minimo       INT NOT NULL DEFAULT 5,          -- umbral de reabastecimiento
  peso_kg            DECIMAL(8,3) NOT NULL DEFAULT 0.500,
  ubicacion          VARCHAR(50) NULL,                -- ubicación en bodega
  sku                VARCHAR(40) NOT NULL UNIQUE,
  fecha_creacion     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_modificacion DATETIME NULL,
  activo             TINYINT(1) NOT NULL DEFAULT 1,
  fecha_eliminacion  DATETIME NULL,                   -- borrado lógico
  id_categoria       INT NULL,                        -- 1 categoría por producto (1:N)
  id_proveedor       INT NOT NULL,                    -- 1 proveedor por producto (1:N)
  CONSTRAINT chk_prod_precio CHECK (precio > 0),
  CONSTRAINT chk_prod_costo  CHECK (costo >= 0),
  CONSTRAINT chk_prod_stock  CHECK (stock >= 0),
  CONSTRAINT fk_prod_cat  FOREIGN KEY (id_categoria) REFERENCES categorias (id_categoria) ON DELETE RESTRICT,
  CONSTRAINT fk_prod_prov FOREIGN KEY (id_proveedor) REFERENCES proveedores (id_proveedor) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE clientes (
  id_cliente          INT AUTO_INCREMENT PRIMARY KEY,
  nombre              VARCHAR(80)  NOT NULL,
  apellido            VARCHAR(80)  NOT NULL,
  email               VARCHAR(150) NOT NULL UNIQUE,
  contrasena          VARCHAR(255) NOT NULL,          -- hash (nunca texto plano)
  direccion_envio     VARCHAR(255) NULL,
  ciudad              VARCHAR(80)  NULL,
  region              VARCHAR(80)  NULL,
  fecha_nacimiento    DATE NULL,
  fecha_registro      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  total_gastado       DECIMAL(14,2) NOT NULL DEFAULT 0,
  fecha_ultimo_pedido DATETIME NULL,
  nivel_lealtad       VARCHAR(10) NOT NULL DEFAULT 'Bronce',
  referido_por        INT NULL,                       -- programa de referidos
  activo              TINYINT(1) NOT NULL DEFAULT 1,
  CONSTRAINT fk_cli_ref FOREIGN KEY (referido_por) REFERENCES clientes (id_cliente) ON DELETE SET NULL
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Ventas y detalle (relación N:M productos <-> ventas)
-- ---------------------------------------------------------------------
CREATE TABLE ventas (
  id_venta        INT AUTO_INCREMENT PRIMARY KEY,
  id_cliente      INT NOT NULL,
  id_sucursal     INT NOT NULL,
  fecha_venta     DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado          ENUM('Pendiente de Pago','Pagado','Procesando','Enviado','Entregado','Cancelado') NOT NULL,
  total           DECIMAL(14,2) NOT NULL DEFAULT 0,
  direccion_envio VARCHAR(255) NULL,
  CONSTRAINT chk_venta_total CHECK (total >= 0),
  CONSTRAINT fk_venta_cli FOREIGN KEY (id_cliente)  REFERENCES clientes (id_cliente)    ON DELETE RESTRICT,
  CONSTRAINT fk_venta_suc FOREIGN KEY (id_sucursal) REFERENCES sucursales (id_sucursal) ON DELETE RESTRICT,
  INDEX idx_ventas_fecha (fecha_venta),
  INDEX idx_ventas_estado (estado)
) ENGINE=InnoDB;

CREATE TABLE detalle_ventas (
  id_detalle                INT AUTO_INCREMENT PRIMARY KEY,
  id_venta                  INT NOT NULL,
  id_producto               INT NOT NULL,
  cantidad                  INT NOT NULL,
  precio_unitario_congelado DECIMAL(12,2) NOT NULL,   -- precio histórico al momento de la compra
  CONSTRAINT chk_det_cant   CHECK (cantidad > 0),
  CONSTRAINT chk_det_precio CHECK (precio_unitario_congelado >= 0),
  CONSTRAINT uq_det_venta_prod UNIQUE (id_venta, id_producto),
  CONSTRAINT fk_det_venta FOREIGN KEY (id_venta)    REFERENCES ventas (id_venta)       ON DELETE CASCADE,
  CONSTRAINT fk_det_prod  FOREIGN KEY (id_producto) REFERENCES productos (id_producto) ON DELETE RESTRICT
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Tablas de apoyo (carritos, visitas, promociones, reseñas, pagos, devoluciones)
-- ---------------------------------------------------------------------
CREATE TABLE carritos (
  id_carrito          INT AUTO_INCREMENT PRIMARY KEY,
  id_cliente          INT NOT NULL,
  fecha_creacion      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  fecha_actualizacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  estado              ENUM('Activo','Convertido','Abandonado') NOT NULL DEFAULT 'Activo',
  CONSTRAINT fk_carrito_cli FOREIGN KEY (id_cliente) REFERENCES clientes (id_cliente) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE carrito_items (
  id_item        INT AUTO_INCREMENT PRIMARY KEY,
  id_carrito     INT NOT NULL,
  id_producto    INT NOT NULL,
  cantidad       INT NOT NULL DEFAULT 1,
  fecha_agregado DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_item_cant CHECK (cantidad > 0),
  CONSTRAINT fk_item_carrito FOREIGN KEY (id_carrito)  REFERENCES carritos (id_carrito)    ON DELETE CASCADE,
  CONSTRAINT fk_item_prod    FOREIGN KEY (id_producto) REFERENCES productos (id_producto) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE visitas_producto (
  id_visita    BIGINT AUTO_INCREMENT PRIMARY KEY,
  id_producto  INT NOT NULL,
  id_cliente   INT NULL,
  fecha_visita DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_vis_prod FOREIGN KEY (id_producto) REFERENCES productos (id_producto) ON DELETE CASCADE,
  CONSTRAINT fk_vis_cli  FOREIGN KEY (id_cliente)  REFERENCES clientes (id_cliente)   ON DELETE SET NULL,
  INDEX idx_vis_fecha (fecha_visita)
) ENGINE=InnoDB;

CREATE TABLE promociones (
  id_promocion        INT AUTO_INCREMENT PRIMARY KEY,
  codigo              VARCHAR(30) NOT NULL UNIQUE,
  id_producto         INT NULL,                        -- NULL = aplica a toda la tienda
  porcentaje_descuento DECIMAL(5,2) NOT NULL,
  fecha_inicio        DATETIME NOT NULL,
  fecha_fin           DATETIME NOT NULL,
  activa              TINYINT(1) NOT NULL DEFAULT 1,
  CONSTRAINT chk_promo_pct CHECK (porcentaje_descuento > 0 AND porcentaje_descuento <= 100),
  CONSTRAINT chk_promo_fechas CHECK (fecha_fin >= fecha_inicio),
  CONSTRAINT fk_promo_prod FOREIGN KEY (id_producto) REFERENCES productos (id_producto) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE resenas (
  id_resena    INT AUTO_INCREMENT PRIMARY KEY,
  id_producto  INT NOT NULL,
  id_cliente   INT NOT NULL,
  calificacion TINYINT NOT NULL,
  comentario   TEXT NULL,
  fecha        DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_res_calif CHECK (calificacion BETWEEN 1 AND 5),
  CONSTRAINT uq_res UNIQUE (id_producto, id_cliente),
  CONSTRAINT fk_res_prod FOREIGN KEY (id_producto) REFERENCES productos (id_producto) ON DELETE CASCADE,
  CONSTRAINT fk_res_cli  FOREIGN KEY (id_cliente)  REFERENCES clientes (id_cliente)   ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE pagos (
  id_pago  INT AUTO_INCREMENT PRIMARY KEY,
  id_venta INT NOT NULL,
  metodo   VARCHAR(30) NOT NULL,
  monto    DECIMAL(14,2) NOT NULL,
  estado   ENUM('Aprobado','Rechazado') NOT NULL,
  fecha    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pago_venta FOREIGN KEY (id_venta) REFERENCES ventas (id_venta) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE devoluciones (
  id_devolucion INT AUTO_INCREMENT PRIMARY KEY,
  id_venta      INT NOT NULL,
  id_producto   INT NOT NULL,
  cantidad      INT NOT NULL,
  motivo        VARCHAR(255) NULL,
  monto_credito DECIMAL(12,2) NOT NULL,
  fecha         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_dev_cant CHECK (cantidad > 0),
  CONSTRAINT fk_dev_venta FOREIGN KEY (id_venta)    REFERENCES ventas (id_venta)       ON DELETE CASCADE,
  CONSTRAINT fk_dev_prod  FOREIGN KEY (id_producto) REFERENCES productos (id_producto) ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE creditos_cliente (
  id_credito INT AUTO_INCREMENT PRIMARY KEY,
  id_cliente INT NOT NULL,
  monto      DECIMAL(12,2) NOT NULL,
  motivo     VARCHAR(255) NULL,
  fecha      DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_cred_cli FOREIGN KEY (id_cliente) REFERENCES clientes (id_cliente) ON DELETE CASCADE
) ENGINE=InnoDB;

-- ---------------------------------------------------------------------
-- Soporte para seguridad (04) y auditoría (05)
-- ---------------------------------------------------------------------
-- Mapa usuario MySQL -> sucursal (filtrado de ventas por sucursal, requisito 19)
CREATE TABLE usuario_sucursal (
  usuario     VARCHAR(32) PRIMARY KEY,
  id_sucursal INT NOT NULL,
  CONSTRAINT fk_us_suc FOREIGN KEY (id_sucursal) REFERENCES sucursales (id_sucursal) ON DELETE CASCADE
) ENGINE=InnoDB;

-- Asignación de roles a nivel de aplicación (MySQL no permite triggers sobre mysql.*)
CREATE TABLE asignacion_roles (
  id_asignacion    INT AUTO_INCREMENT PRIMARY KEY,
  usuario          VARCHAR(32) NOT NULL,
  rol              VARCHAR(50) NOT NULL,
  activo           TINYINT(1) NOT NULL DEFAULT 1,
  fecha_asignacion DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_asig UNIQUE (usuario, rol)
) ENGINE=InnoDB;

-- Tabla de auditoría de precios. Se crea aquí (y se declara de nuevo con IF NOT EXISTS
-- en 05_Triggers.sql) porque 04_Seguridad.sql debe poder otorgar SELECT sobre ella.
CREATE TABLE log_cambios_precio (
  id_log          INT AUTO_INCREMENT PRIMARY KEY,
  id_producto     INT NOT NULL,
  precio_anterior DECIMAL(12,2) NOT NULL,
  precio_nuevo    DECIMAL(12,2) NOT NULL,
  usuario         VARCHAR(100) NULL,
  fecha_cambio    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_lcp_prod (id_producto)
) ENGINE=InnoDB;

SET FOREIGN_KEY_CHECKS = 1;

